"""Split protocols shared by every experiment, so all runs use the same index-generation code.

Each function returns (train_idx, test_idx) as torch.LongTensor, plus a
`meta` dict that gets folded into the result JSON's `split_protocol` info.
"""
from src.utils.reproducibility import replayable_split
from typing import Dict, List, Tuple

import numpy as np
import pandas as pd
import torch

from src.utils.seed import seeded_generator


@replayable_split
def scadanet_track_a_split(
    query_edges: torch.Tensor,
    all_ips: List[str],
    test_ratio: float = 0.2,
    seed: int = 42,
) -> Tuple[torch.Tensor, torch.Tensor, Dict]:
    """SCADANet Track A / "IP-held-out" split: a random 20% of IPs are held out entirely;
    any flow touching a held-out IP as either source or destination becomes test.
    """
    n_ips = len(all_ips)
    g = seeded_generator(seed)
    perm = torch.randperm(n_ips, generator=g)
    n_test_ips = max(1, int(n_ips * test_ratio))
    test_ip_idx = set(perm[:n_test_ips].tolist())

    src, dst = query_edges[0], query_edges[1]
    is_test_flow = torch.tensor([
        (s.item() in test_ip_idx) or (d.item() in test_ip_idx)
        for s, d in zip(src, dst)
    ])
    test_idx = is_test_flow.nonzero(as_tuple=True)[0]
    train_idx = (~is_test_flow).nonzero(as_tuple=True)[0]

    meta = {
        "protocol": "track_a_ip_held_out",
        "n_test_ips": n_test_ips,
        "n_total_ips": n_ips,
        "test_ratio": test_ratio,
    }
    return train_idx, test_idx, meta


@replayable_split
def scadanet_track_b_split(
    df: pd.DataFrame,
    label_col: str,
    ip_diversity_threshold: int = 50,
    src_col: str = "Source",
    test_ratio: float = 0.2,
    seed: int = 42,
) -> Tuple[torch.Tensor, torch.Tensor, Dict]:
    """SCADANet Track B: flow-level random split, restricted to attack types
    generated by a small fixed set of attacker IPs (<= threshold distinct
    source IPs) plus all normal traffic. NOT IP-held-out.
    """
    ip_diversity = df.groupby(label_col)[src_col].nunique().sort_values()
    multi_ip_types = ip_diversity[ip_diversity > ip_diversity_threshold].index.tolist()
    multi_ip_types = [t for t in multi_ip_types if "normal" not in t.strip().lower()]
    single_ip_types = [
        t for t in df[label_col].unique()
        if t not in multi_ip_types and "normal" not in t.strip().lower()
    ]

    is_target_attack = df[label_col].isin(single_ip_types)
    is_normal = df[label_col].str.strip().str.lower().str.contains("normal")
    subset_mask = (is_target_attack | is_normal).to_numpy()
    subset_idx = np.nonzero(subset_mask)[0]

    g = seeded_generator(seed)
    perm = torch.randperm(len(subset_idx), generator=g).numpy()
    n_test = max(1, int(len(subset_idx) * test_ratio))
    test_pos = subset_idx[perm[:n_test]]
    train_pos = subset_idx[perm[n_test:]]

    meta = {
        "protocol": "track_b",
        "single_ip_attack_types": single_ip_types,
        "multi_ip_attack_types_excluded": multi_ip_types,
        "test_ratio": test_ratio,
    }
    return (
        torch.tensor(train_pos, dtype=torch.long),
        torch.tensor(test_pos, dtype=torch.long),
        meta,
    )


@replayable_split
def temporal_window_split(
    df: pd.DataFrame,
    window_col: str = "window",
    label_col: str = None,
    train_fraction: float = 0.7,
) -> Tuple[torch.Tensor, torch.Tensor, Dict]:
    """Chronological split by equal-COUNT window index. Train = windows [0, SPLIT_WINDOW).
    Test = windows [SPLIT_WINDOW, N).

    Works for both SCADANet and BATADAL temporal protocols provided the caller has
    already assigned equal-count window indices to `window_col`.
    """
    n_windows = int(df[window_col].max()) + 1
    split_window = int(n_windows * train_fraction)

    train_mask = (df[window_col] < split_window).to_numpy()
    test_mask = (df[window_col] >= split_window).to_numpy()

    train_pos = np.nonzero(train_mask)[0]
    test_pos = np.nonzero(test_mask)[0]

    meta = {
        "protocol": "temporal",
        "n_windows": n_windows,
        "split_window": split_window,
        "train_fraction": train_fraction,
    }
    if label_col is not None:
        train_types = set(df.loc[train_mask, label_col].unique())
        test_types = set(df.loc[test_mask, label_col].unique())
        meta["unseen_in_train"] = sorted(test_types - train_types)

    return (
        torch.tensor(train_pos, dtype=torch.long),
        torch.tensor(test_pos, dtype=torch.long),
        meta,
    )


@replayable_split
def carve_validation(
    train_idx: torch.Tensor, val_fraction: float = 0.15, seed: int = 42,
) -> Tuple[torch.Tensor, torch.Tensor]:
    """This carves a validation slice OUT of an existing train split (never touches test),
    seeded independently of the outer split's own seeded_generator call so carving
    validation doesn't perturb the train/test boundary itself — call this AFTER the
    split function, on its returned train_idx.
    """
    g = seeded_generator(seed)
    n = train_idx.shape[0]
    perm = torch.randperm(n, generator=g)
    n_val = max(1, int(n * val_fraction))
    val_pos = perm[:n_val]
    fit_pos = perm[n_val:]
    return train_idx[fit_pos], train_idx[val_pos]


@replayable_split
def batadal_static_cv_folds(
    window_labels, n_folds: int = 5, seed: int = 42
) -> List[Tuple[np.ndarray, np.ndarray]]:
    """BATADAL static-CV reference experiment: StratifiedKFold(n_splits=5, shuffle=True,
    random_state=seed) over window_labels — moved verbatim, not re-derived, since
    BATADAL's positive windows are only ~8% and an unstratified split can starve a fold
    of positives entirely.
    """
    from sklearn.model_selection import StratifiedKFold
    skf = StratifiedKFold(n_splits=n_folds, shuffle=True, random_state=seed)
    dummy_x = np.zeros(len(window_labels))
    return list(skf.split(dummy_x, window_labels))
